//! Connection pool and the migration runner -- a compatible port of
//! `apps/api/src/db/pool.ts` and `migrate.ts`.
//!
//! The runner shares the TS runner's `schema_migrations` table, advisory
//! lock key and SQL files, so during the side-by-side phase either server
//! can migrate a database the other one already migrated, and both can
//! start at once. (`sqlx::migrate!` is deliberately not used: its own
//! `_sqlx_migrations` table would re-run every migration on an existing
//! database.)

use sqlx::{Connection, PgConnection, PgPool, Row, postgres::PgPoolOptions};
use thiserror::Error;

/// The SQL migrations, `(file name, SQL)`, sorted by file name. Generated by
/// `build.rs` from `apps/api/src/db/migrations`.
pub const MIGRATIONS: &[(&str, &str)] = include!(concat!(env!("OUT_DIR"), "/migrations.rs"));

/// Arbitrary fixed key for a Postgres advisory lock scoped to migrations --
/// the TS runner's key, so the two runners serialise against each other as
/// well as against themselves. Two API replicas starting at once against a
/// fresh database would otherwise race on `CREATE TABLE IF NOT EXISTS` and
/// one would crash with a duplicate key from Postgres's catalog.
pub const MIGRATION_LOCK_KEY: i64 = 7_272_774;

/// Creates the pool. Like `new pg.Pool(...)`, it connects lazily: an
/// unreachable database surfaces at the first query (the migrations, at
/// startup), not here. Size matches pg's default of 10.
pub fn create_pool(database_url: &str) -> Result<PgPool, sqlx::Error> {
    PgPoolOptions::new()
        .max_connections(10)
        .connect_lazy(database_url)
}

#[derive(Debug, Error)]
pub enum MigrationError {
    /// Same message shape as the TS runner's.
    #[error("Migration {file} failed: {source}")]
    Failed {
        file: String,
        #[source]
        source: sqlx::Error,
    },
    #[error(transparent)]
    Database(#[from] sqlx::Error),
}

/// Applies every migration in [`MIGRATIONS`] not yet recorded in
/// `schema_migrations`, each in its own transaction, under the advisory
/// lock. Returns the file names it applied, in order.
pub async fn run_migrations(pool: &PgPool) -> Result<Vec<String>, MigrationError> {
    run_migrations_from(pool, MIGRATIONS).await
}

/// [`run_migrations`] with an explicit list, so tests can exercise a
/// failing migration. `migrations` must be sorted by name.
pub async fn run_migrations_from(
    pool: &PgPool,
    migrations: &[(&str, &'static str)],
) -> Result<Vec<String>, MigrationError> {
    let mut conn = pool.acquire().await?;
    sqlx::query("SELECT pg_advisory_lock($1)")
        .bind(MIGRATION_LOCK_KEY)
        .execute(&mut *conn)
        .await?;

    let result = apply_pending(&mut conn, migrations).await;

    // Always release the lock, as the TS runner's `finally` does. If the
    // unlock itself fails the connection is suspect: close it rather than
    // hand it back to the pool, since closing the session is what
    // guarantees Postgres drops the lock.
    let unlocked = sqlx::query("SELECT pg_advisory_unlock($1)")
        .bind(MIGRATION_LOCK_KEY)
        .execute(&mut *conn)
        .await;
    if let Err(err) = unlocked {
        let _ = conn.detach().close().await;
        // The migration error, if any, is the more useful one to report.
        result?;
        return Err(err.into());
    }
    result
}

async fn apply_pending(
    conn: &mut PgConnection,
    migrations: &[(&str, &'static str)],
) -> Result<Vec<String>, MigrationError> {
    sqlx::raw_sql(
        "CREATE TABLE IF NOT EXISTS schema_migrations (
            id TEXT PRIMARY KEY,
            applied_at TIMESTAMPTZ NOT NULL DEFAULT now()
        );",
    )
    .execute(&mut *conn)
    .await?;

    let applied: Vec<String> = sqlx::query("SELECT id FROM schema_migrations")
        .fetch_all(&mut *conn)
        .await?
        .iter()
        .map(|row| row.try_get("id"))
        .collect::<Result<_, _>>()?;

    let mut newly_applied = Vec::new();
    for &(file, sql) in migrations {
        if applied.iter().any(|id| id == file) {
            continue;
        }
        apply_one(conn, file, sql)
            .await
            .map_err(|source| MigrationError::Failed {
                file: file.to_owned(),
                source,
            })?;
        newly_applied.push(file.to_owned());
    }
    Ok(newly_applied)
}

async fn apply_one(
    conn: &mut PgConnection,
    file: &str,
    sql: &'static str,
) -> Result<(), sqlx::Error> {
    let mut tx = conn.begin().await?;
    // The simple query protocol, as pg's `client.query(sql)` without
    // parameters uses: a file may hold several statements.
    sqlx::raw_sql(sql).execute(&mut *tx).await?;
    sqlx::query("INSERT INTO schema_migrations (id) VALUES ($1)")
        .bind(file)
        .execute(&mut *tx)
        .await?;
    // Dropping `tx` on an error above rolls it back.
    tx.commit().await
}

#[cfg(test)]
mod tests {
    use super::MIGRATIONS;

    #[test]
    fn embeds_every_migration_file_in_name_order() {
        let names: Vec<&str> = MIGRATIONS.iter().map(|(name, _)| *name).collect();
        let mut sorted = names.clone();
        sorted.sort_unstable();
        assert_eq!(names, sorted);
        assert_eq!(names.first(), Some(&"001_init.sql"));
        assert!(names.len() >= 7, "{names:?}");
        assert!(MIGRATIONS.iter().all(|(_, sql)| !sql.trim().is_empty()));
    }
}
